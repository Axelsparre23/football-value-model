"""Paired bootstrap uncertainty for opening-to-closing market improvements.

Uses the matched fixture file generated by market_movement_backtest.py.
Positive improvement means closing odds scored better than opening odds.
Resamples fixtures (paired) so opening and closing predictions stay matched.

Run: python market_movement_significance.py
"""
from pathlib import Path
import numpy as np
import pandas as pd

INPUT = Path("output/market_movement_fixture_data.csv")
OUTPUT = Path("output")
N_BOOT = 2000
SEED = 20261116
OUTCOMES = {
    "Home": ("Home_open", "Home_close", 0),
    "Draw": ("Draw_open", "Draw_close", 1),
    "Away": ("Away_open", "Away_close", 2),
}


def paired_differences(frame, open_col, close_col, code):
    actual = (frame.Actual.to_numpy(int) == code).astype(float)
    p_open = np.clip(frame[open_col].to_numpy(float), 1e-9, 1 - 1e-9)
    p_close = np.clip(frame[close_col].to_numpy(float), 1e-9, 1 - 1e-9)
    # Positive values mean closing is better.
    brier_gain = (p_open - actual) ** 2 - (p_close - actual) ** 2
    logloss_gain = (
        -actual * np.log(p_open) - (1 - actual) * np.log(1 - p_open)
        + actual * np.log(p_close) + (1 - actual) * np.log(1 - p_close)
    )
    return brier_gain, logloss_gain


def bootstrap_ci(values, rng):
    values = np.asarray(values, dtype=float)
    n = len(values)
    if n < 2:
        return float(np.mean(values)), np.nan, np.nan
    # Chunk bootstrap to avoid allocating an excessive N_BOOT x N array.
    means = np.empty(N_BOOT, dtype=float)
    for start in range(0, N_BOOT, 100):
        count = min(100, N_BOOT - start)
        idx = rng.integers(0, n, size=(count, n))
        means[start:start + count] = values[idx].mean(axis=1)
    return float(values.mean()), float(np.quantile(means, 0.025)), float(np.quantile(means, 0.975))


def main():
    if not INPUT.exists():
        raise FileNotFoundError(
            f"{INPUT} not found. Run python market_movement_backtest.py first."
        )
    data = pd.read_csv(INPUT)
    rng = np.random.default_rng(SEED)
    rows = []

    for outcome, (open_col, close_col, code) in OUTCOMES.items():
        for split_name, groups in [
            ("Overall", [("All", data)]),
            ("League", list(data.groupby("League", sort=True))),
            ("Season", list(data.groupby("Season", sort=True))),
        ]:
            for group_name, group in groups:
                bg, lg = paired_differences(group, open_col, close_col, code)
                b_mean, b_low, b_high = bootstrap_ci(bg, rng)
                l_mean, l_low, l_high = bootstrap_ci(lg, rng)
                rows.append({
                    "Outcome": outcome,
                    "Split": split_name,
                    "Group": str(group_name),
                    "N": len(group),
                    "BrierGain": b_mean,
                    "BrierCI95Low": b_low,
                    "BrierCI95High": b_high,
                    "LogLossGain": l_mean,
                    "LogLossCI95Low": l_low,
                    "LogLossCI95High": l_high,
                })

    result = pd.DataFrame(rows)
    print("Positive gain = closing odds outperform opening odds.")
    print("95% paired-bootstrap confidence intervals; fixture-level resampling.")
    for outcome in OUTCOMES:
        print(f"\n=== {outcome.upper()} ===")
        part = result[(result.Outcome == outcome) & (result.Split == "Overall")]
        for r in part.itertuples():
            print(
                f"N={r.N}: Brier gain={r.BrierGain:+.6f} "
                f"[{r.BrierCI95Low:+.6f}, {r.BrierCI95High:+.6f}] | "
                f"LogLoss gain={r.LogLossGain:+.6f} "
                f"[{r.LogLossCI95Low:+.6f}, {r.LogLossCI95High:+.6f}]"
            )

    print("\n=== BY LEAGUE: BRIER GAIN AND 95% CI ===")
    for r in result[result.Split == "League"].itertuples():
        print(
            f"{r.Outcome:5s} {r.Group:5s} N={r.N:4d} "
            f"{r.BrierGain:+.5f} [{r.BrierCI95Low:+.5f}, {r.BrierCI95High:+.5f}]"
        )
    print("\n=== BY SEASON: BRIER GAIN AND 95% CI ===")
    for r in result[result.Split == "Season"].itertuples():
        print(
            f"{r.Outcome:5s} {r.Group:6s} N={r.N:4d} "
            f"{r.BrierGain:+.5f} [{r.BrierCI95Low:+.5f}, {r.BrierCI95High:+.5f}]"
        )

    OUTPUT.mkdir(parents=True, exist_ok=True)
    result.to_csv(OUTPUT / "market_movement_significance.csv", index=False)
    print("\nSaved output/market_movement_significance.csv")


if __name__ == "__main__":
    main()
